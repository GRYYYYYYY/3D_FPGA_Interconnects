"""Read-only acceptance against the requested paper base; no experimental tools."""
from pathlib import Path
import hashlib, json, subprocess
import pymupdf

P = Path(__file__).resolve().parent
R = P.parents[1]
BASE = '7e63b917f37273f80c03327e024d86b797ee221b'
rel = 'paper/dac2027_integrated/'

def old(path):
    return subprocess.check_output(['git', 'show', BASE + ':' + path], cwd=R)

def sha(raw):
    return hashlib.sha256(raw).hexdigest()

bindings = json.loads((P / 'data_bindings.json').read_text())
for path, digest in bindings['inputs'].items():
    assert sha(old(path)) == digest == sha((R / path).read_bytes()), path
methods = json.loads((P / 'method_binding.json').read_text())
for path, digest in methods.items():
    assert sha(old(path)) == digest == sha((R / path).read_bytes()), path

before = json.loads(old(rel + 'computed_statistics.json'))
after = json.loads((P / 'computed_statistics.json').read_text())
assert all(after[k] == v for k, v in before.items())
prior_claims = json.loads(old(rel + 'claims_accel.json'))
claims = json.loads((P / 'claims_accel.json').read_text())
assert claims[:len(prior_claims)] == prior_claims
for name in ['tables/lstm.tex', 'tables/qor.tex', 'tables/legacy.tex',
             'abstract.txt', 'frontmatter.md']:
    assert old(rel + name) == (P / name).read_bytes(), name
for name in ['native', 'scaling']:
    a = pymupdf.open(stream=old(rel + 'figures/' + name + '.pdf'), filetype='pdf')
    b = pymupdf.open(P / 'figures' / (name + '.pdf'))
    assert len(a) == len(b) == 1
    assert a[0].get_pixmap().samples == b[0].get_pixmap().samples, name

changed = subprocess.check_output(['git', 'diff', '--name-only', BASE], cwd=R, text=True).splitlines()
assert all(p.startswith(rel) or p == 'docs/dac2027_paper_final_revision_20261111.md' for p in changed)
assert not subprocess.check_output(['git', 'diff', BASE, '--', 'paper/dac2027', 'results', 'accel', 'scripts', 'vendor_patches'], cwd=R)
fmt = json.loads((P / 'format_check.json').read_text())
archive = json.loads((P / 'source_archive_build_check.json').read_text())
assert fmt['status'] == archive['status'] == 'passed'
assert (fmt['content_pages'], fmt['reference_pages']) == (6, 1)
assert fmt['pdf_sha256'] == sha((P / 'main.pdf').read_bytes())
assert fmt['source_archive_sha256'] == archive['source_archive_sha256'] == sha((P / 'submission_source.zip').read_bytes())
ai = json.loads((P / 'ai_usage_evidence.json').read_text())
assert ai['model_identifiers'] == ['gpt-6-astra', 'gpt-6.1-sol']
tex = (P / 'main.tex').read_text()
assert 'before ALT shift/cache/selector tuning' not in tex
assert 'was frozen before its own new ALT qualification and timing' in tex
assert 'STRICT reads the native RRGraphView directly' in tex
assert 'frontier width is not GPU occupancy' in tex
assert r'\section*{Content Generated by AI}' in tex
assert 'ICCAD66269.2025.11240893' in (P / 'main.bbl').read_text()
out = dict(status='passed', revision_base=BASE, frozen_inputs_unchanged=len(bindings['inputs']),
           method_sources_unchanged=len(methods), previous_statistics_unchanged=len(before),
           previous_claims_unchanged=len(prior_claims), added_claims=[c['claim_id'] for c in claims[len(prior_claims):]],
           original_tables_and_figure_rasters_unchanged=True, original_paper_and_research_files_unchanged=True,
           title_abstract_contributions_unchanged=True, pages='6 content + 1 references only',
           pdf_sha256=fmt['pdf_sha256'], source_archive_sha256=fmt['source_archive_sha256'],
           new_experiments=0, human_review_attested=False, author_check_items='AUTHOR_CHECKS.md', submitted=False)
(P / 'final_revision_check.json').write_text(json.dumps(out, indent=2) + '\n')
print(json.dumps(out, indent=2))
